#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const scanRoot = "src";
const cataloguePath = path.join(root, "docs/COMPONENT-CATALOGUE.md");
const catalogueName = "docs/COMPONENT-CATALOGUE.md";

const isComponentName = (name) =>
  /^[A-Z][A-Za-z0-9]*$/.test(name) && /[a-z]/.test(name);

function sourceFiles(directory, prefix) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const relative = `${prefix}${entry.name}`;
      if (entry.isDirectory())
        return sourceFiles(path.join(directory, entry.name), `${relative}/`);
      return /\.tsx?$/.test(entry.name) ? [relative] : [];
    })
    .sort();
}

function modifiersOf(node) {
  return ts.getModifiers
    ? (ts.getModifiers(node) ?? [])
    : (node.modifiers ?? []);
}

const hasExport = (node) =>
  modifiersOf(node).some(
    (modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword,
  );

function exportedComponentNames(file) {
  const text = readFileSync(path.join(root, file), "utf8");
  const source = ts.createSourceFile(
    file,
    text,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TSX,
  );
  const names = new Set();
  for (const statement of source.statements) {
    if (
      (ts.isFunctionDeclaration(statement) ||
        ts.isClassDeclaration(statement)) &&
      hasExport(statement) &&
      statement.name &&
      isComponentName(statement.name.text)
    ) {
      names.add(statement.name.text);
    } else if (ts.isVariableStatement(statement) && hasExport(statement)) {
      for (const declaration of statement.declarationList.declarations) {
        if (
          ts.isIdentifier(declaration.name) &&
          isComponentName(declaration.name.text)
        ) {
          names.add(declaration.name.text);
        }
      }
    } else if (
      ts.isExportDeclaration(statement) &&
      statement.exportClause &&
      ts.isNamedExports(statement.exportClause)
    ) {
      for (const element of statement.exportClause.elements) {
        if (isComponentName(element.name.text)) names.add(element.name.text);
      }
    } else if (
      ts.isExportAssignment(statement) &&
      ts.isIdentifier(statement.expression) &&
      isComponentName(statement.expression.text)
    ) {
      names.add(statement.expression.text);
    }
  }
  return [...names].sort();
}

function buildCatalogue() {
  const sections = sourceFiles(path.join(root, scanRoot), `${scanRoot}/`)
    .map((file) => ({ file, names: exportedComponentNames(file) }))
    .filter((section) => section.names.length > 0);
  const total = sections.reduce(
    (sum, section) => sum + section.names.length,
    0,
  );
  const lines = [
    "# Component catalogue",
    "",
    "Regenerate with `npm run ui:catalogue`; do not edit this file by hand.",
    "`npm run check` verifies it matches the source.",
    "",
    `${total} components in ${sections.length} files: an exported function, class or const declared or re-exported under \`src/\` counts as a component when its exported name starts with an uppercase letter and contains a lowercase letter, and a named default export counts under its declared name.`,
    "",
  ];
  for (const section of sections) {
    lines.push(`## \`${section.file}\``, "");
    for (const name of section.names) lines.push(`- \`${name}\``);
    lines.push("");
  }
  return { text: `${lines.join("\n").trimEnd()}\n`, total, sections };
}

const checkMode = process.argv.includes("--check");
const { text, total, sections } = buildCatalogue();

if (checkMode) {
  const current = existsSync(cataloguePath)
    ? readFileSync(cataloguePath, "utf8")
    : null;
  if (current === text) {
    console.log(
      `Component catalogue is up to date: ${total} components in ${sections.length} files.`,
    );
    process.exit(0);
  }
  console.error(
    `${catalogueName} does not match the source; run npm run ui:catalogue.`,
  );
  if (current === null) {
    console.error("Drift: catalogue file is missing.");
  } else {
    const expected = new Set(text.split("\n"));
    const present = new Set(current.split("\n"));
    for (const line of current.split("\n")) {
      if (!expected.has(line) && line !== "")
        console.error(`stale:    ${line}`);
    }
    for (const line of text.split("\n")) {
      if (!present.has(line) && line !== "") console.error(`missing:  ${line}`);
    }
  }
  process.exit(1);
}

writeFileSync(cataloguePath, text);
console.log(
  `Wrote ${catalogueName}: ${total} components in ${sections.length} files.`,
);
