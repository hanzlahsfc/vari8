#!/usr/bin/env python3
"""Write icm/05-build/PROGRAM.md from graph.json, graph-summary.json and timeline.md (run by generate.py after program.py)."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from program_data import OUTROOT, PRS  # noqa: E402

OUT = f"{OUTROOT}/icm/05-build"

G = json.load(open(f"{OUT}/graph.json"))
S = json.load(open(f"{OUT}/graph-summary.json"))
TL = open(f"{OUT}/timeline.md").read().strip()
BY_KEY = {c["key"]: c for c in G["cards"]}
lines = []
w = lines.append

waves = [
    ("W0, done", "DEC-AUTH, DEC-AUTH-REVIEW (D16a), AUD-REDUCTION, AUD-PRR-BASELINE, PR-02 (#57 merged at `55a0f08`)."),
    ("W1, in flight outside the graph since about 02:24", "PR-05 (#58), PR-03A (#59), PR-03B (#60), PR-P1 (#61), PR-X1 (#62). Their verify and merge cards are on the board."),
    ("W2, to the 05:00 checkpoint", "PR-04 dev runtime and seed, PR-01 canvas takeover, PR-T2 consent test cuts. Then the verifiers of W1 and W2 and the merges in dependency order."),
    ("W3, foundation finish", "PR-R0 helper dedupe, PR-SV4 invitations, PR-W1 identity home, PR-03 toolchain, PR-M0 schema v2, PR-31 PWA and mobile."),
    ("W4, models", "PR-M1 to PR-M9, PR-MEDIA. Service and validator PRs; PR-M0 is the only schema writer before them (D34). Each owns its seed file."),
    ("W5, wiring", "PR-W0 data seam, PR-SV1 to PR-SV3, PR-W2 to PR-W10, PR-MSG. Up to seven in parallel, capped at 5 Devin builders."),
    ("W6, reduction and close", "PR-R1 delete superseded (then `frontend/`), PR-R2 schema reduction, PR-R3 flags and dependencies, PR-X2 index rebuild, PR-D1 README and setup, then GATE-PRR, GATE-FINAL, GATE-CLEAN."),
]

w("# PROGRAM: Vari8-Beta merge\n")
w("Program lead: meliodas. Plan: `icm/03-plan/output/PLAN.md` v2. Single source: `icm/05-build/tools/program_data.py`; every table below is generated by `program.py` and `program_md.py`. Live state: `icm/05-build/BLACKBOARD.md`. How to run a lane: `icm/05-build/RUNBOOK.md`.\n")
w("## Mission and the rule that does not bend\n")
w("The canvas (`frontend/`) is taken over exactly as it looks today; the backend is refactored and reduced to serve it. Every wired screen passes the D32 parity gate against `icm/04-briefing/shots/` at 1440x900 and 390x844. Everything ships on GitHub: issue, branch, PR, local check, independent SHIP, merge, cleanup.\n")
w("## Waves\n")
w("| Wave | Content |\n| --- | --- |")
for a, b in waves:
    w(f"| {a} | {b} |")
w("")
w("## Dependency graph (merge-to-build edges per PR)\n")
w("Every PR is three cards: build, verify (plus a security verify for auth, schema and media PRs), merge. A build card's parents are the merge cards of the PRs it depends on. Verifiers of screen PRs also wait for the PR-P1 merge (harness) and the PR-04 merge (seed). Full card graph with ids: `icm/05-build/graph.json` and `icm/05-build/cards/board-ids.tsv`.\n")
w("| PR | Depends on | Builder | Verifier |\n| --- | --- | --- | --- |")
for p in PRS:
    v = BY_KEY.get(f'{p["id"]}:verify', {})
    sv = BY_KEY.get(f'{p["id"]}:secverify')
    ver = v.get("assignee", "-") + (f', {sv["assignee"]} (security)' if sv else "")
    b = "Devin via yamato, gear " + str(p.get("gear")) if p["who"] == "yamato" else (p["who"] or f'external {p.get("builder_model")}, issue #{p.get("issue")}')
    w(f'| {p["id"]} | {", ".join(p["deps"]) or "-"} | {b} | {ver} |')
w("")
w("## Routing\n")
w("| Work | Lane | Model |\n| --- | --- | --- |")
for row in [
    ("Builders", "yamato drives Devin; the card names the gear SOUL and skills", "Devin swe-2-max (driver deepseek-v4.1-flash)"),
    ("Bulk mechanical (test cuts, index rebuild)", "tenten, shikamaru", "deepseek-v4.1-flash"),
    ("Per-PR behavior and parity verify", "neji (urokodaki for PR-P1 and AUD-REDUCTION, built on claude-haiku-5-5)", "claude-haiku-5-5 (claude-opus-5-5)"),
    ("Security verify (auth, schema, media, invitations)", "shinobu", "claude-haiku-5-5"),
    ("Integration (merge cards) and GATE-CLEAN", "kakashi profile, escalation meliodas", "deepseek-v4.1-flash"),
    ("Production-readiness gate", "urokodaki", "claude-opus-5-5, medium"),
    ("Final judgement, once", "minato", "gpt-6.1-sol"),
]:
    w(f"| {row[0]} | {row[1]} | {row[2]} |")
w("\nMax 5 Devin builders at once: `icm/05-build/tools/devin-slot.sh` counts every running `devin` binary, including the three started outside the graph.\n")
w("## Gates\n")
for g in [
    "Per PR: `verify-local.sh` exit 0 (D13), live receipt per role at both widths with unauthorized routes failing closed, parity on the PR's screens, every listed matrix row PASS, verdict comment `SHIP <id> <sha>` from a model other than the builder's.",
    "Per merge: `integrate.sh` refuses without a SHIP for the current head, test-merges with the base and runs the fast gate on the merge result.",
    "Program: GATE-PRR (production-readiness on the integrated tip, from the 02:30 baseline), GATE-FINAL (minato, SHIP or HOLD), GATE-CLEAN (no open program issues or PRs, no stray branches, worktrees or `app_*` databases).",
]:
    w(f"- {g}")
w("")
w("## Timeline\n")
w("Simulated by the generator: graph cards start at 03:00 once the orchestrator releases the board, each card takes its estimate, external builds land at their estimate from 02:24, merges serialize on one lock, at most 5 Devin builders. Build start and merge time per PR:\n")
w(TL)
w("")
cp = dict(S["checkpoint"])
w("### 05:00 checkpoint\n")
w("Done by 05:00 in the simulation: " + ", ".join(f"`{k}` {t}" for k, t in S["checkpoint"]) + ".\n")
pr01 = next((d for c, d in ((c["key"], c["done"]) for c in G["cards"]) if c == "PR-01:merge"), None)
pr01_txt = pr01.split(" ")[-1] if pr01 else "unscheduled"
in_cp = "PR-01:merge" in cp
w("What the checkpoint shows: PR-02 merged; the parity harness, the test cuts, the hooks fixes, the index, Better Auth (PR-05) and the dev seed (PR-04) merged; D16a recorded. "
  f"PR-01 (canvas on the root app) waits for the verified harness (PR-P1 merge) and merges at {pr01_txt} in the simulation, "
  + ("inside the 05:00 set. " if in_cp else "after 05:00, so the checkpoint shows PR-01 built or in build with its PR open, and the program continues. ")
  + "Program finish in the simulation: " + S["finish"] + ".\n")
w("## Self-check\n")
n_prs = len(PRS)
builds = sum(1 for c in G["cards"] if c["kind"] == "build")
verifies = {c["pr"] for c in G["cards"] if c["kind"] == "verify"}
merges = sum(1 for c in G["cards"] if c["kind"] == "merge")
same_model = []
for p in PRS:
    bm = p.get("builder_model") or "swe-2-max"
    for k in ("verify", "secverify"):
        v = BY_KEY.get(f'{p["id"]}:{k}')
        if v and v["model"] and v["model"] in bm:
            same_model.append(p["id"])
rc = 1 if S["problems"] else 0
w("| Check | Result |\n| --- | --- |")
w(f"| Every PLAN v2 PR has a card | {n_prs} PR sections, {builds} build cards, {merges} merge cards |")
w(f"| Every card has a verifier card | {len(verifies)} of {n_prs} PRs have a verify card; {S['by_kind'].get('verify', 0)} verify cards in total (security verifies included) |")
w(f"| Verifier model differs from the builder model | {'yes for every PR' if not same_model else 'NO: ' + ', '.join(same_model)} |")
w(f"| Coverage ledger has zero unmapped rows | {S['unmapped']} unmapped of {sum(S['ledger'].values())} rows ({', '.join(f'{k} {v}' for k, v in S['ledger'].items())}) |")
w(f"| Dependency graph has no cycles | {S['cycles']} cycles in {S['cards']} cards (topological sort in `program.py`) |")
w(f"| Timeline fits 05:00 | 05:00 is a checkpoint, not the end: {len(S['checkpoint'])} cards done by 05:00, PR-01 merged at {pr01_txt}; the full program finishes {S['finish']} |")
w(f"| Generator gate | `python3 icm/05-build/tools/program.py` problems: {len(S['problems'])} (exit {rc}) |")
w("")
open(f"{OUT}/PROGRAM.md", "w").write("\n".join(lines) + "\n")
print(f"PROGRAM.md written; generator exit {rc}; same-model verifiers {same_model}")
sys.exit(1 if rc or same_model or S["unmapped"] or S["cycles"] else 0)
