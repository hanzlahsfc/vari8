"use client";

import { useActionState } from "react";

import {
  createCheckInRuleAction,
  generateCheckInRuleAction,
  setCheckInRuleStatusAction,
  type StaffCheckInGenerateState,
  type StaffCheckInRuleLifecycleState,
  type StaffCheckInRuleState,
} from "@/app/workspace/[workspaceId]/clients/[clientProfileId]/checkins/actions";
import type { CheckInScheduleRuleItem } from "@/lib/checkin/schedules";

const WEEKDAYS = [
  "MONDAY",
  "TUESDAY",
  "WEDNESDAY",
  "THURSDAY",
  "FRIDAY",
  "SATURDAY",
  "SUNDAY",
] as const;

const WEEKDAY_LABEL: Record<string, string> = {
  MONDAY: "Monday",
  TUESDAY: "Tuesday",
  WEDNESDAY: "Wednesday",
  THURSDAY: "Thursday",
  FRIDAY: "Friday",
  SATURDAY: "Saturday",
  SUNDAY: "Sunday",
};

function fmtMinutes(minutes: number): string {
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}`;
}

/**
 * CHECK-IN-RECURRENCE-I1 (decision #114) — staff recurring-rule panel.
 * Conspicuous nonautomatic copy: generated dates exist ONLY because a
 * staff member explicitly generated them; the schedule never
 * replenishes itself. Creation requires an explicitly confirmed
 * timezone; generation reports truthful coverage (examined-through /
 * created / already-generated / skipped conflicts / unrepresentable).
 */
export function CheckInScheduleRules({
  workspaceId,
  clientProfileId,
  options,
  rules,
  canWrite,
}: {
  workspaceId: string;
  clientProfileId: string;
  options: Array<{
    position: number;
    formName: string;
    versionSeq: number;
  }>;
  rules: CheckInScheduleRuleItem[];
  canWrite: boolean;
}) {
  const [createState, createAction, createPending] = useActionState<
    StaffCheckInRuleState,
    FormData
  >(createCheckInRuleAction, { ok: "idle" });
  const [lifeState, lifeAction, lifePending] = useActionState<
    StaffCheckInRuleLifecycleState,
    FormData
  >(setCheckInRuleStatusAction, { ok: "idle" });
  const [genState, genAction, genPending] = useActionState<
    StaffCheckInGenerateState,
    FormData
  >(generateCheckInRuleAction, { ok: "idle" });

  const suggestedZone = Intl.DateTimeFormat().resolvedOptions().timeZone;

  return (
    <section className="tracker-section" data-testid="checkin-rules-section">
      <h2 className="tracker-section__title">Recurring Check-Ins</h2>
      <p className="app-lede">
        Weekly Check-Ins are generated by staff action only — the schedule is
        not automatic and does not replenish itself. If staff do not extend it,
        no future dates are created.
      </p>

      {rules.length > 0 ? (
        <ul className="tracker-list" data-testid="checkin-rules-list">
          {rules.map((rule) => (
            <li
              key={rule.ruleId}
              className="tracker-list__row"
              data-testid={`checkin-rule-${rule.status.toLowerCase()}`}
            >
              <span className="tracker-list__title">
                {rule.formName} — every {WEEKDAY_LABEL[rule.weekday]}{" "}
                {fmtMinutes(rule.localTimeMinutes)} ({rule.timezone})
              </span>
              <span className="tracker-list__sub">
                {rule.status}
                {" · From "}
                {rule.startDate}
                {rule.endDate ? ` to ${rule.endDate}` : ""}
                {" · Generated through "}
                {rule.generatedThrough ?? "nothing generated yet"}
              </span>
              {canWrite && rule.status !== "ENDED" ? (
                <span className="tracker-list__actions">
                  <form action={genAction} style={{ display: "inline" }}>
                    <input
                      type="hidden"
                      name="workspaceId"
                      value={workspaceId}
                    />
                    <input
                      type="hidden"
                      name="clientProfileId"
                      value={clientProfileId}
                    />
                    <input type="hidden" name="ruleId" value={rule.ruleId} />
                    <button
                      type="submit"
                      className="auth-button"
                      disabled={genPending || rule.status === "PAUSED"}
                    >
                      Generate upcoming dates
                    </button>
                  </form>
                  <form action={lifeAction} style={{ display: "inline" }}>
                    <input
                      type="hidden"
                      name="workspaceId"
                      value={workspaceId}
                    />
                    <input
                      type="hidden"
                      name="clientProfileId"
                      value={clientProfileId}
                    />
                    <input type="hidden" name="ruleId" value={rule.ruleId} />
                    <input
                      type="hidden"
                      name="ruleAction"
                      value={rule.status === "PAUSED" ? "resume" : "pause"}
                    />
                    <button
                      type="submit"
                      className="auth-button"
                      disabled={lifePending}
                    >
                      {rule.status === "PAUSED" ? "Resume" : "Pause"}
                    </button>
                  </form>
                  <form action={lifeAction} style={{ display: "inline" }}>
                    <input
                      type="hidden"
                      name="workspaceId"
                      value={workspaceId}
                    />
                    <input
                      type="hidden"
                      name="clientProfileId"
                      value={clientProfileId}
                    />
                    <input type="hidden" name="ruleId" value={rule.ruleId} />
                    <input type="hidden" name="ruleAction" value="end" />
                    <button
                      type="submit"
                      className="auth-button"
                      disabled={lifePending}
                    >
                      End
                    </button>
                  </form>
                </span>
              ) : null}
            </li>
          ))}
        </ul>
      ) : (
        <p className="app-lede" data-testid="checkin-rules-empty">
          No recurring Check-In rules for this client.
        </p>
      )}

      <div aria-live="polite">
        {createState.ok === true ? (
          <p className="daily-todo" role="status" data-testid="rule-created">
            {createState.status === "replaced"
              ? "Recurring rule replaced."
              : "Recurring rule created."}
          </p>
        ) : null}
        {createState.ok === false ? (
          <p className="daily-errors" role="alert">
            {createState.message}
          </p>
        ) : null}
        {lifeState.ok === true ? (
          <p
            className="daily-todo"
            role="status"
            data-testid={`rule-${lifeState.status}`}
          >
            {lifeState.status === "paused"
              ? "Rule paused — no new dates will be generated."
              : lifeState.status === "resumed"
                ? "Rule resumed — generate upcoming dates when ready."
                : "Rule ended — pending generated dates were cancelled."}
          </p>
        ) : null}
        {lifeState.ok === false ? (
          <p className="daily-errors" role="alert">
            {lifeState.message}
          </p>
        ) : null}
        {genState.ok === true ? (
          <p
            className="daily-todo"
            role="status"
            data-testid="rule-generate-result"
          >
            {genState.status === "generated"
              ? `Coverage examined through ${genState.examinedThrough} — ${genState.created} created, ${genState.alreadyGenerated} already generated` +
                (genState.skippedConflicts.length > 0
                  ? `, ${genState.skippedConflicts.length} skipped (conflict: ${genState.skippedConflicts.join(", ")})`
                  : "") +
                (genState.unrepresentable.length > 0
                  ? `, ${genState.unrepresentable.length} unrepresentable dates`
                  : "")
              : genState.status === "paused"
                ? "Rule is paused — nothing was generated."
                : "Rule has ended — nothing was generated."}
          </p>
        ) : null}
        {genState.ok === false ? (
          <p className="daily-errors" role="alert">
            {genState.message}
          </p>
        ) : null}
      </div>

      {canWrite ? (
        <form
          action={createAction}
          className="tracker-page"
          data-testid="checkin-rule-form"
        >
          <input type="hidden" name="workspaceId" value={workspaceId} />
          <input type="hidden" name="clientProfileId" value={clientProfileId} />
          <div className="daily-field">
            <label htmlFor="checkin-rule-version">Check-In form</label>
            <select
              id="checkin-rule-version"
              name="formVersionPosition"
              className="catalog-search__input"
              disabled={createPending || options.length === 0}
              required
            >
              {options.map((o) => (
                <option key={o.position} value={String(o.position)}>
                  {o.formName} — v{o.versionSeq}
                </option>
              ))}
            </select>
          </div>
          <div className="daily-field">
            <label htmlFor="checkin-rule-weekday">Day of week</label>
            <select
              id="checkin-rule-weekday"
              name="weekday"
              className="catalog-search__input"
              disabled={createPending || options.length === 0}
              required
            >
              {WEEKDAYS.map((d) => (
                <option key={d} value={d}>
                  {WEEKDAY_LABEL[d]}
                </option>
              ))}
            </select>
          </div>
          <div className="daily-field">
            <label htmlFor="checkin-rule-time">Local time</label>
            <input
              id="checkin-rule-time"
              name="localTime"
              className="catalog-search__input"
              type="time"
              disabled={createPending || options.length === 0}
              required
            />
          </div>
          <div className="daily-field">
            <label htmlFor="checkin-rule-tz">Client timezone</label>
            <input
              id="checkin-rule-tz"
              name="timezone"
              className="catalog-search__input"
              type="text"
              defaultValue={suggestedZone}
              placeholder="e.g. America/New_York"
              disabled={createPending || options.length === 0}
              required
              data-testid="checkin-rule-tz"
            />
          </div>
          <div className="daily-field">
            <label htmlFor="checkin-rule-tz-confirm">
              <input
                id="checkin-rule-tz-confirm"
                name="timezoneConfirmed"
                type="checkbox"
                value="1"
                required
              />{" "}
              I confirm this is the client’s timezone
            </label>
          </div>
          <div className="daily-field">
            <label htmlFor="checkin-rule-start">Start date</label>
            <input
              id="checkin-rule-start"
              name="startDate"
              className="catalog-search__input"
              type="date"
              disabled={createPending || options.length === 0}
              required
            />
          </div>
          <div className="daily-field">
            <label htmlFor="checkin-rule-end">End date (optional)</label>
            <input
              id="checkin-rule-end"
              name="endDate"
              className="catalog-search__input"
              type="date"
              disabled={createPending || options.length === 0}
            />
          </div>
          <button
            type="submit"
            className="auth-button"
            style={{ minHeight: "44px" }}
            disabled={createPending || options.length === 0}
            data-testid="checkin-rule-submit"
          >
            {createPending ? "Creating…" : "Create recurring rule"}
          </button>
        </form>
      ) : null}
    </section>
  );
}
