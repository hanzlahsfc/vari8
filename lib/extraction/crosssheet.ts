import type { ExtractionCell } from "./contracts";

/**
 * Cross-sheet candidate links.
 *
 * Only two SAFE value classes are matched: (1) reference-data names (foods,
 * exercises) and (2) curated static template labels. Arbitrary values from
 * client-bearing sheets are never matched, copied, or revealed; that analysis is
 * deferred until redaction (Phase 11). A verbatim text match is a verified text
 * match, not proof of a semantic relationship.
 */

export type SheetCells = { slug: string; cells: ExtractionCell[] };
export type MatchLocation = { slug: string; row: number; col: number; count: number };
export type MatchEntry = { value: string; locations: MatchLocation[] };

export type CrossSheetInput = {
  sheets: SheetCells[];
  foodNames: ReadonlySet<string>;
  exerciseNames: ReadonlySet<string>;
  safeLabels: ReadonlySet<string>;
};

export type CrossSheetData = {
  foods: MatchEntry[];
  exercises: MatchEntry[];
  labels: MatchEntry[];
  totals: { foods: number; exercises: number; labels: number };
};

const MAX_LIST = 200;

function collect(
  sheets: SheetCells[],
  names: ReadonlySet<string>,
  excludeSourceSlug: string | null,
): MatchEntry[] {
  const map = new Map<string, Map<string, MatchLocation>>();
  for (const sheet of sheets) {
    const bySheet = new Map<string, MatchLocation>();
    for (const cell of sheet.cells) {
      const value = cell.text.trim();
      if (!names.has(value)) continue;
      const existing = bySheet.get(value);
      if (existing) existing.count += 1;
      else bySheet.set(value, { slug: sheet.slug, row: cell.row, col: cell.col, count: 1 });
    }
    for (const [value, location] of bySheet) {
      const entry = map.get(value) ?? new Map<string, MatchLocation>();
      entry.set(sheet.slug, location);
      map.set(value, entry);
    }
  }

  const result: MatchEntry[] = [];
  for (const [value, locations] of map) {
    const list = [...locations.values()].sort((a, b) => a.slug.localeCompare(b.slug) || a.row - b.row || a.col - b.col);
    const touchesOther = list.some((location) => location.slug !== excludeSourceSlug);
    if (!touchesOther) continue;
    result.push({ value, locations: list });
  }
  result.sort((a, b) => a.value.localeCompare(b.value));
  return result;
}

function collectLabels(sheets: SheetCells[], labels: ReadonlySet<string>): MatchEntry[] {
  const map = new Map<string, Map<string, MatchLocation>>();
  for (const sheet of sheets) {
    for (const cell of sheet.cells) {
      const value = cell.text.trim();
      if (!labels.has(value)) continue;
      const entry = map.get(value) ?? new Map<string, MatchLocation>();
      const existing = entry.get(sheet.slug);
      if (existing) existing.count += 1;
      else entry.set(sheet.slug, { slug: sheet.slug, row: cell.row, col: cell.col, count: 1 });
      map.set(value, entry);
    }
  }
  const result: MatchEntry[] = [];
  for (const [value, locations] of map) {
    const list = [...locations.values()].sort((a, b) => a.slug.localeCompare(b.slug) || a.row - b.row);
    if (list.length >= 2) result.push({ value, locations: list });
  }
  result.sort((a, b) => a.value.localeCompare(b.value));
  return result;
}

export function buildCrossSheetData(input: CrossSheetInput): CrossSheetData {
  const foods = collect(input.sheets, input.foodNames, "nutrition-database");
  const exercises = collect(input.sheets, input.exerciseNames, "exercise-database");
  const labels = collectLabels(input.sheets, input.safeLabels);
  return {
    foods,
    exercises,
    labels,
    totals: { foods: foods.length, exercises: exercises.length, labels: labels.length },
  };
}

function renderEntries(entries: MatchEntry[]): string {
  const lines: string[] = [];
  for (const entry of entries.slice(0, MAX_LIST)) {
    const where = entry.locations
      .map((location) => `${location.slug}:r${location.row}c${location.col}${location.count > 1 ? ` (+${location.count - 1})` : ""}`)
      .join(", ");
    lines.push(`- \`${entry.value}\` — ${where}`);
  }
  if (entries.length > MAX_LIST) {
    lines.push(`- … ${entries.length - MAX_LIST} more (list truncated; counts above are complete)`);
  }
  if (lines.length === 0) lines.push("- _(none found)_");
  return lines.join("\n");
}

export function renderCrossSheetMarkdown(data: CrossSheetData): string {
  const clientSheets = ["daily-tracker", "dashboard", "timeline", "menses", "peaking", "showday"];
  return `# Cross-sheet candidate links

Generated by the sheet extractor. **Candidate** links only: a verbatim text match
proves the text is shared, not that the sheets are semantically wired.

Method: only two safe value classes are matched — reference-data names (foods,
exercises) and curated static template labels. All locations are \`slug:rROWcCOL\`.
Listing is capped at ${MAX_LIST} entries per section; the totals are complete.

## Reference-data text matches — foods

Food names from the Nutrition Database that also appear in another sheet. Verified
**text** match; the semantic relationship (e.g. a meal-plan row using that food) is
unverified.

- matched food names: ${data.totals.foods}

${renderEntries(data.foods)}

## Reference-data text matches — exercises

Exercise names from the Exercise Database that also appear in another sheet.
Verified **text** match; the TRAINING relationship is unverified.

- matched exercise names: ${data.totals.exercises}

${renderEntries(data.exercises)}

## Shared static labels

Curated static template labels appearing in two or more sheets.

- shared labels: ${data.totals.labels}

${renderEntries(data.labels)}

## Client-bearing values — intentionally omitted

Arbitrary value matching across client-bearing sheets (${clientSheets.join(", ")}) is
**not** performed and no such values are printed; that requires the redaction
ruleset (Phase 11). Only locations/counts of reference names and static labels are
reported here.
`;
}
